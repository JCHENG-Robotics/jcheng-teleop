"""Input replay: re-derive actions from recorded input with the same core.

Replay uses a fresh `Conditioner`/`ActionMapper` and a fake clock; it has no
gateway, DDS or device port. Divergence is a finding, never a reason to edit
the capture.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from ..core.conditioning import Conditioner
from ..core.mapper import ActionMapper
from ..core.model import InputSample, Mode
from ..core.profile import ResolvedProfile
from .capture_reader import CaptureData

_COMPARE = (
    "mode",
    "purpose",
    "deadman",
    "seq",
    "t_source_ns",
    "joint_positions_rad",
    "joint_velocities_rad_s",
    "gripper_normalized",
    "gripper_valid",
    "frame_id",
    "profile_id",
    "profile_hash",
)


@dataclass(frozen=True)
class Divergence:
    tick_id: int
    field: str
    recorded: Any
    derived: Any

    def to_dict(self) -> dict[str, Any]:
        return {
            "tick_id": self.tick_id,
            "field": self.field,
            "recorded": self.recorded,
            "derived": self.derived,
        }


@dataclass
class ReplayReport:
    capture_id: str
    inputs_read: int = 0
    actions_recorded: int = 0
    motion_compared: int = 0
    stop_skipped: int = 0
    missing_input: int = 0
    rejected: int = 0
    defects: list[str] = field(default_factory=list)
    divergences: list[Divergence] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.defects and not self.divergences

    def to_dict(self) -> dict[str, Any]:
        return {
            "capture_id": self.capture_id,
            "inputs_read": self.inputs_read,
            "actions_recorded": self.actions_recorded,
            "motion_compared": self.motion_compared,
            "stop_skipped": self.stop_skipped,
            "missing_input": self.missing_input,
            "rejected": self.rejected,
            "defects": list(self.defects),
            "divergences": [item.to_dict() for item in self.divergences],
            "status": "ok" if self.ok else "diverged",
        }


def _sample_from_row(row: dict[str, Any]) -> InputSample:
    return InputSample(
        schema=str(row["schema"]),
        source_id=str(row["source_id"]),
        source_class=str(row["source_class"]),
        seq=int(row["seq"]),
        t_source_ns=int(row["t_source_ns"]),
        t_host_mono_ns=int(row["t_host_mono_ns"]),
        mode=Mode.parse(str(row["mode"])),
        joint_positions_rad=tuple(float(item) for item in row.get("joint_positions_rad", [])),
        joint_velocities_rad_s=tuple(
            float(item) for item in row.get("joint_velocities_rad_s", [])
        ),
        gripper_normalized=(
            None
            if row.get("gripper_normalized") is None
            else float(row["gripper_normalized"])
        ),
        gripper_valid=bool(row.get("gripper_valid", False)),
        deadman=bool(row["deadman"]),
        calibration_id=row.get("calibration_id"),
        profile_id=row.get("profile_id"),
    )


def _equal(left: Any, right: Any) -> bool:
    if isinstance(left, list) and isinstance(right, (list, tuple)):
        return len(left) == len(right) and all(_equal(a, b) for a, b in zip(left, right))
    if isinstance(left, (int, float)) and isinstance(right, (int, float)):
        return float(left) == float(right)
    return left == right


def replay_streams(
    streams: dict[str, list[dict[str, Any]]],
    resolved: ResolvedProfile,
    *,
    capture_id: str = "",
) -> ReplayReport:
    report = ReplayReport(capture_id=capture_id)
    conditioner = Conditioner(resolved)
    mapper = ActionMapper(resolved)
    inputs = {row.get("tick_id"): row for row in streams.get("input", [])}
    report.inputs_read = len(streams.get("input", []))
    for row in streams.get("action", []):
        report.actions_recorded += 1
        if row.get("purpose") == "stop":
            # Stop intents are generated by the session, not by the mapper.
            report.stop_skipped += 1
            continue
        tick = row.get("tick_id")
        input_row = inputs.get(tick)
        if input_row is None:
            report.missing_input += 1
            report.defects.append(f"action tick {tick} has no input row")
            continue
        try:
            sample = _sample_from_row(input_row)
            derived = mapper.map(conditioner.process(sample)).to_dict()
        except Exception as exc:
            report.rejected += 1
            report.defects.append(f"tick {tick}: replay rejected the recorded sample: {exc}")
            continue
        report.motion_compared += 1
        for name in _COMPARE:
            recorded = row.get(name)
            if not _equal(recorded, derived.get(name)):
                report.divergences.append(
                    Divergence(
                        tick_id=int(tick),
                        field=name,
                        recorded=recorded,
                        derived=derived.get(name),
                    )
                )
    return report


def replay_capture(capture: CaptureData, resolved: ResolvedProfile) -> ReplayReport:
    return replay_streams(capture.streams, resolved, capture_id=capture.capture_id)
